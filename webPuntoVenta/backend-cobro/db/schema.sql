-- =====================================================================
-- Esquema de base de datos de la aplicación web de cobro (front desk).
--
-- Reutiliza el mismo servidor PostgreSQL de la carpeta de punto de venta
-- siguiendo la convención del equipo: cada aplicación usa su propio
-- esquema (webcobro) dentro de la misma base, en vez de crear tablas
-- sueltas en public.
-- =====================================================================

CREATE SCHEMA IF NOT EXISTS webcobro;

-- Clientes que llegan a recepción.
CREATE TABLE IF NOT EXISTS webcobro.clientes (
    id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre    TEXT NOT NULL,
    membresia TEXT NOT NULL DEFAULT 'Básica',
    telefono  TEXT NOT NULL DEFAULT ''
);

-- Vigencia y estado del socio, para validar membresía vencida / inactiva.
--   activo = false        → el socio está inactivo (no puede reservar como socio).
--   vigencia_hasta = null → sin fecha de vencimiento (no expira).
ALTER TABLE webcobro.clientes ADD COLUMN IF NOT EXISTS activo BOOLEAN NOT NULL DEFAULT TRUE;
ALTER TABLE webcobro.clientes ADD COLUMN IF NOT EXISTS vigencia_hasta DATE;
-- Correo del socio (opcional): lo captura el módulo administrativo y debe ser
-- único cuando se proporciona. Los socios viejos de cobro no lo tenían.
ALTER TABLE webcobro.clientes ADD COLUMN IF NOT EXISTS correo TEXT;
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'clientes_correo_unique'
          AND conrelid = 'webcobro.clientes'::regclass
    ) THEN
        ALTER TABLE webcobro.clientes
            ADD CONSTRAINT clientes_correo_unique UNIQUE (correo);
    END IF;
END $$;

-- Clases que se pueden cobrar en recepción.
CREATE TABLE IF NOT EXISTS webcobro.clases (
    id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre TEXT NOT NULL,
    precio NUMERIC(10, 2) NOT NULL CHECK (precio >= 0)
);

-- Reservaciones que se muestran en el tablero de recepción.
CREATE TABLE IF NOT EXISTS webcobro.reservas (
    id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente TEXT NOT NULL,
    tipo    TEXT NOT NULL DEFAULT 'cliente'
        CHECK (tipo IN ('cliente', 'visitante')),
    clase   TEXT NOT NULL,
    hora    TEXT NOT NULL,
    fecha   TEXT NOT NULL DEFAULT '',  -- YYYY-MM-DD; la fecha de cada
                                      -- reserva coincide con un horario
                                      -- real (modulo de horarios).
    estado  TEXT NOT NULL DEFAULT 'pendiente'
        CHECK (estado IN ('pendiente', 'pagado', 'asistido', 'cancelado')),
    precio  NUMERIC(10, 2) NOT NULL DEFAULT 0 CHECK (precio >= 0)
);

-- Si la tabla venía de la versión anterior, se agrega la columna tipo
-- (socio registrado o visitante) sin perder los registros guardados.
ALTER TABLE webcobro.reservas
    ADD COLUMN IF NOT EXISTS tipo TEXT NOT NULL DEFAULT 'cliente';

-- Si la tabla venía de la versión anterior (sin fecha), se agrega la columna
-- fecha (YYYY-MM-DD). Las reservas viejas quedan con fecha vacia: no
-- apuntan a ningun horario real, por lo que ya no son reservables y el
-- backend las ignora al validar cupos y duplicados.
ALTER TABLE webcobro.reservas
    ADD COLUMN IF NOT EXISTS fecha TEXT NOT NULL DEFAULT '';

-- Vinculo estable con la sesion de MongoDB y estado independiente del cupo.
-- Una reserva puede estar pendiente de pago y, al mismo tiempo, en lista de
-- espera; por eso estado_cupo no reutiliza la columna financiera estado.
ALTER TABLE webcobro.reservas
    ADD COLUMN IF NOT EXISTS horario_id TEXT NOT NULL DEFAULT '';

ALTER TABLE webcobro.reservas
    ADD COLUMN IF NOT EXISTS estado_cupo TEXT NOT NULL DEFAULT 'confirmada';

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'reservas_estado_cupo_check'
          AND conrelid = 'webcobro.reservas'::regclass
    ) THEN
        ALTER TABLE webcobro.reservas
            ADD CONSTRAINT reservas_estado_cupo_check
            CHECK (estado_cupo IN ('confirmada', 'espera'));
    END IF;
END $$;

-- Modelo de CUPO: varias personas pueden reservar la misma clase a la misma
-- hora (el límite es la capacidad de la clase, validada en el backend). Por eso
-- se elimina el índice único (clase, hora) de la versión anterior de slots.
DROP INDEX IF EXISTS webcobro.reservas_clase_hora_idx;

-- Índice para listar/buscar las reservas de una clase en una fecha y hora
-- concretas (la clave de consistencia con el modulo de horarios).
CREATE INDEX IF NOT EXISTS reservas_clase_fecha_hora_idx
    ON webcobro.reservas (clase, fecha, hora);

CREATE INDEX IF NOT EXISTS reservas_horario_cupo_idx
    ON webcobro.reservas (horario_id, estado_cupo, estado, id);

-- Pagos registrados desde el modal de cobro.
-- Cada pago se liga a la reservación que se cobró (reserva_id). El cliente_id
-- es opcional: el visitante no tiene ficha en webcobro.clientes, solo se guarda
-- su nombre tomado de la reservación.
CREATE TABLE IF NOT EXISTS webcobro.pagos (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Folio visible en el comprobante de cobro. Se genera al confirmar el pago.
    folio               VARCHAR(24),
    reserva_id          INTEGER REFERENCES webcobro.reservas (id) ON DELETE RESTRICT,
    cliente_id          INTEGER REFERENCES webcobro.clientes (id) ON DELETE RESTRICT,
    cliente_nombre      TEXT NOT NULL,
    monto               NUMERIC(10, 2) NOT NULL CHECK (monto >= 0),
    -- Mismas formas de pago que maneja el Punto de Venta.
    metodo_pago         TEXT NOT NULL DEFAULT 'efectivo'
                        CHECK (metodo_pago IN ('efectivo', 'tarjeta', 'transferencia')),
    -- Efectivo entregado y cambio devuelto: solo aplican a pagos en efectivo.
    efectivo_recibido   NUMERIC(10, 2) DEFAULT NULL
                        CHECK (efectivo_recibido IS NULL OR efectivo_recibido >= 0),
    cambio              NUMERIC(10, 2) DEFAULT NULL
                        CHECK (cambio IS NULL OR cambio >= 0),
    -- Referencia de la transferencia, cuando la forma de pago es esa.
    referencia          TEXT DEFAULT NULL,
    -- Nombre del recepcionista que confirmó el cobro.
    usuario             TEXT DEFAULT NULL,
    creado_en           TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Si la tabla venía de la versión anterior (pagos solo por cliente), se agrega
-- la columna reserva_id y se quita la obligatoriedad de cliente_id sin perder
-- los registros guardados.
ALTER TABLE webcobro.pagos
    ADD COLUMN IF NOT EXISTS reserva_id INTEGER REFERENCES webcobro.reservas (id);

ALTER TABLE webcobro.pagos
    ALTER COLUMN cliente_id DROP NOT NULL;

-- Si la tabla venía de la versión anterior (solo efectivo), se agregan las
-- columnas de forma de pago que ya usa el Punto de Venta.
ALTER TABLE webcobro.pagos
    ADD COLUMN IF NOT EXISTS metodo_pago TEXT NOT NULL DEFAULT 'efectivo';

ALTER TABLE webcobro.pagos
    ADD COLUMN IF NOT EXISTS efectivo_recibido NUMERIC(10, 2) DEFAULT NULL;

ALTER TABLE webcobro.pagos
    ADD COLUMN IF NOT EXISTS cambio NUMERIC(10, 2) DEFAULT NULL;

ALTER TABLE webcobro.pagos
    ADD COLUMN IF NOT EXISTS referencia TEXT DEFAULT NULL;

-- Datos del comprobante. Se mantienen opcionales para no invalidar pagos
-- históricos creados antes de que existiera el servicio de ticket.
ALTER TABLE webcobro.pagos
    ADD COLUMN IF NOT EXISTS folio VARCHAR(24);

ALTER TABLE webcobro.pagos
    ADD COLUMN IF NOT EXISTS usuario TEXT DEFAULT NULL;

-- El CHECK de forma de pago se agrega solo si no existe (para poder re-ejecutar).
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'pagos_metodo_pago_check'
          AND conrelid = 'webcobro.pagos'::regclass
    ) THEN
        ALTER TABLE webcobro.pagos
            ADD CONSTRAINT pagos_metodo_pago_check
            CHECK (metodo_pago IN ('efectivo', 'tarjeta', 'transferencia'));
    END IF;
END $$;

CREATE INDEX IF NOT EXISTS pagos_creado_en_idx ON webcobro.pagos (creado_en);

-- Los pagos nuevos siempre reciben un folio único. El índice parcial permite
-- conservar sin cambios los registros históricos cuyo folio todavía es NULL.
CREATE UNIQUE INDEX IF NOT EXISTS pagos_folio_idx
    ON webcobro.pagos (folio)
    WHERE folio IS NOT NULL;

-- Una reservación no puede cobrarse dos veces.
CREATE UNIQUE INDEX IF NOT EXISTS pagos_reserva_id_idx
    ON webcobro.pagos (reserva_id)
    WHERE reserva_id IS NOT NULL;

-- Empleados que usan el reloj checador (módulo de asistencia).
CREATE TABLE IF NOT EXISTS webcobro.empleados (
    codigo TEXT PRIMARY KEY,
    nombre TEXT NOT NULL,
    rol    TEXT NOT NULL DEFAULT 'recepción'
);

-- Marcas de entrada y salida del reloj checador.
CREATE TABLE IF NOT EXISTS webcobro.asistencias (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      -- EMP-101 (empleado) o CLI-N (socio). Sin FK: la existencia de la persona
    -- se valida en el backend contra webcobro.empleados / webcobro.clientes.
    codigo    TEXT NOT NULL,
    nombre    TEXT NOT NULL,
    tipo      TEXT NOT NULL CHECK (tipo IN ('entrada', 'salida')),
    creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS asistencias_codigo_idx ON webcobro.asistencias (codigo, creado_en DESC);
