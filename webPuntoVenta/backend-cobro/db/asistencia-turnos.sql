-- Migración aditiva y explícita. No ejecutar automáticamente ni sembrar turnos.
BEGIN;
ALTER TABLE webcobro.asistencias ADD COLUMN IF NOT EXISTS estado TEXT
  CHECK (estado IN ('puntual', 'retardo', 'inasistencia', 'sin_turno'));
ALTER TABLE webcobro.asistencias ADD COLUMN IF NOT EXISTS automatica BOOLEAN NOT NULL DEFAULT false;
CREATE TABLE IF NOT EXISTS webcobro.turnos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo TEXT NOT NULL REFERENCES webcobro.empleados(codigo),
  dia_semana INTEGER NOT NULL CHECK (dia_semana BETWEEN 0 AND 6),
  hora_inicio TIME NOT NULL,
  retardo_minutos INTEGER NOT NULL CHECK (retardo_minutos >= 0),
  falta_minutos INTEGER NOT NULL CHECK (falta_minutos > retardo_minutos),
  activo BOOLEAN NOT NULL DEFAULT true,
  UNIQUE (codigo, dia_semana, hora_inicio)
);
CREATE INDEX IF NOT EXISTS turnos_dia_idx ON webcobro.turnos(dia_semana, codigo) WHERE activo;
COMMIT;