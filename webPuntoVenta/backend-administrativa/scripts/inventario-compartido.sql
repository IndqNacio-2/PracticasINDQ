-- Migración aditiva de UnionApp. Requiere la tabla existente del POS.
-- Aplicar explícitamente en un entorno autorizado; no ejecutar db:setup.
CREATE TABLE IF NOT EXISTS webpontoventa.inventory_movements (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id INTEGER NOT NULL REFERENCES webpontoventa.products (id) ON DELETE RESTRICT,
    type VARCHAR(10) NOT NULL CHECK (type IN ('entrada', 'salida', 'merma')),
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    reason VARCHAR(300) NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);